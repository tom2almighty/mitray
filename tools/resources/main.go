// resources builds a Windows resource object from mitray.svg without a C toolchain.
package main

import (
	"bytes"
	"encoding/binary"
	"flag"
	"fmt"
	"image"
	"image/png"
	"log"
	"os"
	"path/filepath"
	"strings"

	"github.com/akavel/rsrc/rsrc"
	"github.com/srwiley/oksvg"
	"github.com/srwiley/rasterx"
)

const (
	sourceSVGFile = "mitray.svg"
	baseFillColor = "#34619B"
	colorRunning  = "#34619B" // Core running, proxy and TUN off (also EXE icon).
	colorActive   = "#D7AC7F" // Core running, proxy or TUN enabled (RGB 215, 172, 127).
	colorStopped  = "#D81E06" // Core stopped (RGB 216, 30, 6).
)

var iconSizes = []int{16, 20, 24, 32, 48, 64, 96, 128, 256}

type iconVariant struct {
	name  string
	color string
}

var variants = []iconVariant{
	{name: "mitray.ico", color: colorRunning},
	{name: "mitray_on.ico", color: colorActive},
	{name: "mitray_off.ico", color: colorStopped},
}

func main() {
	arch := flag.String("arch", "amd64", "Windows architecture")
	flag.Parse()

	svgBytes, err := os.ReadFile(sourceSVGFile)
	if err != nil {
		log.Fatal(err)
	}
	tmpDir, err := os.MkdirTemp("", "mitray-rsrc-*")
	if err != nil {
		log.Fatal(err)
	}
	defer os.RemoveAll(tmpDir)

	paths := make([]string, len(variants))
	ids := make([]int, len(variants))
	next := 2 // Manifest consumes resource ID 1.
	for i, v := range variants {
		icoBytes, err := buildICOFromSVG(string(svgBytes), v.color, iconSizes)
		if err != nil {
			log.Fatalf("render %s: %v", v.name, err)
		}
		outPath := filepath.Join(tmpDir, v.name)
		if err := os.WriteFile(outPath, icoBytes, 0600); err != nil {
			log.Fatal(err)
		}
		paths[i] = outPath
		ids[i] = next
		next += 1 + len(iconSizes)
	}

	if err := rsrc.Embed("cmd/mitray/rsrc_windows_"+*arch+".syso", *arch, "app.manifest", strings.Join(paths, ",")); err != nil {
		log.Fatal(err)
	}
	code := fmt.Sprintf("// Code generated by tools/resources; DO NOT EDIT.\npackage resources\n\nvar IconIDs = [...]int{%d, %d, %d}\n", ids[0], ids[1], ids[2])
	if err := os.WriteFile("internal/resources/resources.go", []byte(code), 0644); err != nil {
		log.Fatal(err)
	}
}

func recolorSVG(svgText, hexColor string) (string, error) {
	if !strings.Contains(svgText, baseFillColor) {
		return "", fmt.Errorf("source SVG does not contain base color %s", baseFillColor)
	}
	return strings.ReplaceAll(svgText, baseFillColor, hexColor), nil
}

func renderSVG(svgText string, size int) (*image.NRGBA, error) {
	icon, err := oksvg.ReadIconStream(strings.NewReader(svgText))
	if err != nil {
		return nil, err
	}
	w, h := float64(size), float64(size)
	icon.SetTarget(0, 0, w, h)
	rgba := image.NewRGBA(image.Rect(0, 0, size, size))
	scanner := rasterx.NewScannerGV(size, size, rgba, rgba.Bounds())
	raster := rasterx.NewDasher(size, size, scanner)
	icon.Draw(raster, 1.0)
	return unpremultiply(rgba), nil
}

func unpremultiply(src *image.RGBA) *image.NRGBA {
	b := src.Bounds()
	dst := image.NewNRGBA(b)
	for y := b.Min.Y; y < b.Max.Y; y++ {
		for x := b.Min.X; x < b.Max.X; x++ {
			so := src.PixOffset(x, y)
			do := dst.PixOffset(x, y)
			r, g, bl, a := src.Pix[so], src.Pix[so+1], src.Pix[so+2], src.Pix[so+3]
			switch a {
			case 0:
				dst.Pix[do], dst.Pix[do+1], dst.Pix[do+2], dst.Pix[do+3] = 0, 0, 0, 0
			case 255:
				dst.Pix[do], dst.Pix[do+1], dst.Pix[do+2], dst.Pix[do+3] = r, g, bl, 255
			default:
				ai := int(a)
				dst.Pix[do] = uint8(min(255, (int(r)*255+ai/2)/ai))
				dst.Pix[do+1] = uint8(min(255, (int(g)*255+ai/2)/ai))
				dst.Pix[do+2] = uint8(min(255, (int(bl)*255+ai/2)/ai))
				dst.Pix[do+3] = a
			}
		}
	}
	return dst
}

func encodeDIB32(img *image.NRGBA) []byte {
	w := img.Bounds().Dx()
	h := img.Bounds().Dy()
	maskRowBytes := ((w + 31) / 32) * 4
	xorSize := w * h * 4
	maskSize := maskRowBytes * h

	var buf bytes.Buffer
	buf.Grow(40 + xorSize + maskSize)
	// BITMAPINFOHEADER (40 bytes)
	_ = binary.Write(&buf, binary.LittleEndian, uint32(40))
	_ = binary.Write(&buf, binary.LittleEndian, int32(w))
	_ = binary.Write(&buf, binary.LittleEndian, int32(h*2)) // XOR + AND height
	_ = binary.Write(&buf, binary.LittleEndian, uint16(1))  // planes
	_ = binary.Write(&buf, binary.LittleEndian, uint16(32)) // bitCount
	_ = binary.Write(&buf, binary.LittleEndian, uint32(0))  // BI_RGB
	_ = binary.Write(&buf, binary.LittleEndian, uint32(xorSize+maskSize))
	_ = binary.Write(&buf, binary.LittleEndian, int32(0))
	_ = binary.Write(&buf, binary.LittleEndian, int32(0))
	_ = binary.Write(&buf, binary.LittleEndian, uint32(0))
	_ = binary.Write(&buf, binary.LittleEndian, uint32(0))

	// Bottom-up BGRA XOR bitmap
	for y := h - 1; y >= 0; y-- {
		for x := range w {
			off := img.PixOffset(x, y)
			r, g, b, a := img.Pix[off], img.Pix[off+1], img.Pix[off+2], img.Pix[off+3]
			buf.Write([]byte{b, g, r, a})
		}
	}

	// Bottom-up 1bpp AND mask (1 = transparent where alpha == 0)
	mask := make([]byte, maskSize)
	for y := range h {
		srcY := h - 1 - y
		rowStart := y * maskRowBytes
		for x := range w {
			off := img.PixOffset(x, srcY)
			if img.Pix[off+3] == 0 {
				mask[rowStart+x/8] |= 0x80 >> uint(x%8)
			}
		}
	}
	buf.Write(mask)
	return buf.Bytes()
}

func buildICOFromSVG(svgText, hexColor string, sizes []int) ([]byte, error) {
	colored, err := recolorSVG(svgText, hexColor)
	if err != nil {
		return nil, err
	}
	payloads := make([][]byte, len(sizes))
	for i, size := range sizes {
		img, err := renderSVG(colored, size)
		if err != nil {
			return nil, fmt.Errorf("size %d: %w", size, err)
		}
		if size >= 256 {
			var pngBuf bytes.Buffer
			if err := png.Encode(&pngBuf, img); err != nil {
				return nil, err
			}
			payloads[i] = pngBuf.Bytes()
		} else {
			payloads[i] = encodeDIB32(img)
		}
	}

	var out bytes.Buffer
	// ICONDIR (6 bytes)
	_ = binary.Write(&out, binary.LittleEndian, uint16(0))
	_ = binary.Write(&out, binary.LittleEndian, uint16(1))
	_ = binary.Write(&out, binary.LittleEndian, uint16(len(sizes)))

	offset := uint32(6 + len(sizes)*16)
	for i, size := range sizes {
		dim := byte(size)
		if size >= 256 {
			dim = 0
		}
		out.WriteByte(dim)
		out.WriteByte(dim)
		out.WriteByte(0) // colorCount
		out.WriteByte(0) // reserved
		_ = binary.Write(&out, binary.LittleEndian, uint16(1))
		_ = binary.Write(&out, binary.LittleEndian, uint16(32))
		_ = binary.Write(&out, binary.LittleEndian, uint32(len(payloads[i])))
		_ = binary.Write(&out, binary.LittleEndian, offset)
		offset += uint32(len(payloads[i]))
	}
	for _, p := range payloads {
		out.Write(p)
	}
	return out.Bytes(), nil
}
